const storageKey = 'cedarbay-language';
const recipient = 'support@cedarbay.cc';
let language = 'en';
let introduction = '';
let copyState = '';
try { if (localStorage.getItem(storageKey) === 'zh') language = 'zh'; } catch { /* Language switching remains usable if storage is blocked. */ }

const form = document.querySelector('#waitlist-form');
const confirmation = document.querySelector('#email-next-step');
const emailLink = document.querySelector('#open-email');
const manualCopy = document.querySelector('#manual-copy');
const copyStatus = document.querySelector('#copy-status');
const languageButton = document.querySelector('.language-switch');

function setMultilineText(element, value) {
  element.replaceChildren(...value.split('\n').flatMap((line, index) => index ? [document.createElement('br'), document.createTextNode(line)] : [document.createTextNode(line)]));
}

function applyLanguage() {
  const copy = translations[language];
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.title = copy.pageTitle;
  document.querySelector('meta[name="description"]').content = copy.metaDescription;
  document.querySelector('meta[property="og:title"]').content = copy.pageTitle;
  document.querySelector('meta[property="og:description"]').content = copy.metaDescription;
  document.querySelectorAll('[data-i18n]').forEach(element => setMultilineText(element, copy[element.dataset.i18n]));
  for (const attribute of ['placeholder', 'alt', 'aria']) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
      element.setAttribute(attribute === 'aria' ? 'aria-label' : attribute, copy[element.dataset[`i18n${attribute[0].toUpperCase()}${attribute.slice(1)}`]]);
    });
  }
  languageButton.querySelector('span').textContent = language === 'en' ? '中文' : 'EN';
  languageButton.setAttribute('aria-label', language === 'en' ? '切换到中文' : 'Switch to English');
  form.elements.name.setCustomValidity('');
  form.elements.email.setCustomValidity('');
  if (!confirmation.hidden) prepareIntroduction();
  copyStatus.textContent = copyState ? copy[copyState] : '';
}

function prepareIntroduction() {
  const name = form.elements.name.value.trim();
  const email = form.elements.email.value.trim();
  const service = form.elements.service;
  const project = form.elements.project.value.trim();
  const subject = language === 'zh' ? 'Cedar Bay Inc 项目候补申请' : 'Cedar Bay Inc project waitlist';
  const body = language === 'zh'
    ? `你好，Cedar Bay Inc 团队：\n\n我希望加入项目候补名单。\n\n姓名：${name}\n联系邮箱：${email}\n服务方向：${service.selectedOptions[0].textContent}\n\n项目介绍：\n${project || '希望一起梳理需求。'}\n\n期待与你们交流！`
    : `Hello Cedar Bay Inc,\n\nI'd like to join your project waitlist.\n\nName: ${name}\nContact email: ${email}\nInterested in: ${service.value}\n\nProject idea:\n${project || "I'd love to explore the details together."}\n\nLooking forward to connecting!`;
  introduction = `${language === 'zh' ? '收件人' : 'To'}: ${recipient}\n${language === 'zh' ? '主题' : 'Subject'}: ${subject}\n\n${body}`;
  emailLink.href = `mailto:${recipient}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  manualCopy.value = introduction;
}

languageButton.addEventListener('click', () => {
  language = language === 'en' ? 'zh' : 'en';
  try { localStorage.setItem(storageKey, language); } catch { /* Storage is optional. */ }
  copyState = '';
  manualCopy.hidden = true;
  applyLanguage();
});

form.addEventListener('input', event => event.target.setCustomValidity?.(''));
form.addEventListener('invalid', event => {
  const field = event.target;
  if (field.name === 'name') field.setCustomValidity(translations[language].invalidName);
  if (field.name === 'email') field.setCustomValidity(translations[language].invalidEmail);
}, true);

form.addEventListener('submit', event => {
  event.preventDefault();
  form.elements.name.value = form.elements.name.value.trim();
  form.elements.email.value = form.elements.email.value.trim();
  if (!form.elements.name.value) form.elements.name.setCustomValidity(translations[language].invalidName);
  if (!form.reportValidity()) return;
  prepareIntroduction();
  form.hidden = true;
  confirmation.hidden = false;
  confirmation.focus({ preventScroll: true });
  // A mailto handoff is not proof of delivery; the next step remains visible.
  emailLink.click();
});

document.querySelector('#edit-details').addEventListener('click', () => {
  confirmation.hidden = true;
  form.hidden = false;
  manualCopy.hidden = true;
  copyState = '';
  copyStatus.textContent = '';
  form.elements.name.focus({ preventScroll: true });
});

document.querySelector('#copy-intro').addEventListener('click', async () => {
  try {
    await navigator.clipboard.writeText(introduction);
    copyState = 'copied';
    manualCopy.hidden = true;
  } catch {
    copyState = 'copyManual';
    manualCopy.hidden = false;
    manualCopy.focus();
    manualCopy.select();
  }
  copyStatus.textContent = translations[language][copyState];
});

const privacyDialog = document.querySelector('#privacy-dialog');
document.querySelector('#privacy-button').addEventListener('click', () => {
  privacyDialog.showModal();
  document.body.classList.add('no-scroll');
});
privacyDialog.querySelector('.dialog-close').addEventListener('click', () => privacyDialog.close());
privacyDialog.addEventListener('click', event => {
  if (event.target !== privacyDialog) return;
  const bounds = privacyDialog.getBoundingClientRect();
  if (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom) privacyDialog.close();
});
privacyDialog.addEventListener('close', () => document.body.classList.remove('no-scroll'));
document.querySelector('#year').textContent = String(new Date().getFullYear());
applyLanguage();
form.querySelector('button[type="submit"]').disabled = false;
